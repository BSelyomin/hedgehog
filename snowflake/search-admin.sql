-- Run once in the NEW Snowflake account as ACCOUNTADMIN.
-- Grants the existing app role access to a dedicated source schema and warehouse.
-- The setup script creates the source table and search service as HEDGEHOG_AI.
USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS HEDGEHOG;
CREATE SCHEMA IF NOT EXISTS HEDGEHOG.REPORTING;
CREATE WAREHOUSE IF NOT EXISTS HEDGEHOG_SEARCH_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 300;

GRANT USAGE ON DATABASE HEDGEHOG TO ROLE HEDGEHOG_AI;
GRANT USAGE ON SCHEMA HEDGEHOG.REPORTING TO ROLE HEDGEHOG_AI;
GRANT CREATE TABLE, CREATE CORTEX SEARCH SERVICE
  ON SCHEMA HEDGEHOG.REPORTING TO ROLE HEDGEHOG_AI;
GRANT USAGE ON WAREHOUSE HEDGEHOG_SEARCH_WH TO ROLE HEDGEHOG_AI;
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE HEDGEHOG_AI;
